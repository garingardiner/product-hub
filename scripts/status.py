#!/usr/bin/env python3
"""Validate initiative manifests, check phase gates, and regenerate ROADMAP.md.

Usage: python scripts/status.py   (requires: pip install pyyaml)
"""
import sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
PHASES = ["discovery", "feedback", "spec", "engineering", "gtm", "done", "parked"]
FORMS = {"repo-md", "data", "claude-doc", "claude-artifact", "figma", "asana", "drive", "other"}
STATUSES = {"not-started", "draft", "in-review", "approved", "synthesized", "superseded"}
# Artifacts that must be complete to leave each phase, and the status that counts as complete.
GATES = {
    "discovery": {"concept": {"approved"}},
    "feedback": {"feedback": {"synthesized", "approved"}},
    "spec": {"project_spec": {"approved"}, "ux_spec": {"approved"}, "success_metrics": {"approved"}},
    "engineering": {"engineering_scope": {"approved"}},
    "gtm": {"feature_benefits": {"approved"}},
}

def load(p):
    return yaml.safe_load(p.read_text(encoding="utf-8")) if p.exists() else {}

def data_checks(folder, phase):
    """Content checks on structured data that the gate depends on."""
    issues = []
    if phase == "feedback":
        fb = load(folder / "feedback.yaml")
        if any(h.get("verdict") in (None, "open") for h in fb.get("hypotheses", [])):
            issues.append("hypotheses without a verdict")
        if not (fb.get("sizing") or {}).get("customer_count"):
            issues.append("sizing.customer_count missing")
    if phase == "spec":
        for m in load(folder / "metrics.yaml").get("metrics", []):
            if not all(m.get(k) for k in ("target", "method", "review_date")):
                issues.append(f"metric '{m.get('name')}' missing target/method/review_date")
    if phase == "engineering":
        p0 = {r["id"] for r in load(folder / "requirements.yaml").get("requirements", [])
              if r.get("priority") == "P0" and r.get("status") != "dropped"}
        scope = load(folder / "scope.yaml")
        covered = {rid for i in scope.get("items", []) if i.get("status") != "cut" for rid in i.get("requirements", [])}
        if p0 - covered:
            issues.append(f"P0 not in scope: {', '.join(sorted(p0 - covered))}")
        if not (scope.get("qa") or {}).get("approach"):
            issues.append("QA approach missing")
    return issues

def check(folder):
    m = load(folder / "initiative.yaml")
    errors, gate = [], []
    if m.get("slug") != folder.name:
        errors.append(f"slug '{m.get('slug')}' != folder name")
    if m.get("phase") not in PHASES:
        errors.append(f"invalid phase '{m.get('phase')}'")
    for key, a in (m.get("artifacts") or {}).items():
        if a.get("form") not in FORMS:
            errors.append(f"{key}: invalid form '{a.get('form')}'")
        if a.get("status") not in STATUSES:
            errors.append(f"{key}: invalid status '{a.get('status')}'")
        if a.get("status") not in ("not-started", None):
            loc = a.get("path") if a.get("form") in ("repo-md", "data") else a.get("link")
            if not loc:
                errors.append(f"{key}: status '{a['status']}' but no path/link")
            elif a.get("form") in ("repo-md", "data") and not (folder / loc).exists():
                errors.append(f"{key}: file '{loc}' not found")
    skip = m.get("skip_phases") or []
    for s in skip:
        if s not in GATES:
            errors.append(f"skip_phases: '{s}' is not a phase")
    # A phase marked not needed has no gate: the initiative can move straight on from it
    if m.get("phase") not in skip:
        for key, ok in GATES.get(m.get("phase"), {}).items():
            st = (m.get("artifacts") or {}).get(key, {}).get("status", "missing")
            if st not in ok:
                gate.append(f"{key} is {st}")
        gate += data_checks(folder, m.get("phase"))
    return m, errors, gate

def next_phase(m):
    """The next phase this initiative still needs, skipping phases marked not needed ('' if none)."""
    order = list(GATES)  # discovery .. gtm
    phase, skip = m.get("phase"), set(m.get("skip_phases") or [])
    if phase not in order:
        return ""
    return next((p for p in order[order.index(phase) + 1:] if p not in skip), "")

def main():
    rows, failed = [], False
    folders = sorted(p for p in (ROOT / "initiatives").iterdir() if p.is_dir() and not p.name.startswith("_"))
    for f in folders:
        m, errors, gate = check(f)
        for e in errors:
            print(f"ERROR {f.name}: {e}")
        failed |= bool(errors)
        rows.append((m.get("priority", "P9"), PHASES.index(m["phase"]) if m.get("phase") in PHASES else 99, m, gate))
    rows.sort(key=lambda r: (r[0], -r[1]))
    out = ["# Roadmap", "", "_Generated by `scripts/status.py`. Do not edit by hand._", "",
           "| Priority | Initiative | Phase | Owner | Target | Ready to advance? | Blockers |",
           "|---|---|---|---|---|---|---|"]
    for pri, _, m, gate in rows:
        ready = ("archived" if m.get("archived") else "n/a" if m.get("phase") in ("done", "parked")
                 else ("✅ yes" if not gate else "❌ " + "; ".join(gate)))
        out.append(f"| {pri} | [{m.get('name')}](initiatives/{m.get('slug')}/initiative.yaml) | {m.get('phase')} | "
                   f"{m.get('owner', '')} | {m.get('target_release', '')} | {ready} | {'; '.join(m.get('blockers') or []) or '—'} |")
    (ROOT / "ROADMAP.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"ROADMAP.md updated ({len(rows)} initiatives)")
    sys.exit(1 if failed else 0)

if __name__ == "__main__":
    main()
